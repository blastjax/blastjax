#!/usr/bin/env python3
"""
Copy every application table from the local SQLite file into PostgreSQL (Neon).

Read-only against SQLite -- it never writes back, and it does not touch
``backend/db.py`` or any app code. The app still runs on SQLite after this;
this script only populates the Postgres side.

This is a point-in-time snapshot of the schema as it existed for that one
migration, not a living mirror of the Postgres schema -- ``src_counts`` needs
every table below to also exist in the SQLite file, so a table born straight
in Postgres after the migration (e.g. ``company``) cannot be added here
without breaking a re-run; column-level drift since (e.g. ``payslip.company``,
the retired ``payslip.employee_hdmf``/``payslip.sss``, or
``payslip_default``/``payslip_default_settings`` gaining a ``company`` column
and losing their single-tenant keys -- the latter also drops the
``payslip_default_settings.id`` column SQLite still has) is reflected here for
documentation but would need the SQLite file to actually match to re-run
cleanly.

The Postgres schema mirrors the SQLite DDL in ``data/budget.sqlite``
column-for-column (types, PRIMARY KEY, UNIQUE, CHECK, and FOREIGN KEY):

  - INTEGER PRIMARY KEY AUTOINCREMENT -> INTEGER GENERATED BY DEFAULT AS
    IDENTITY (sequence resynced from MAX(id) after the copy)
  - REAL                 -> DOUBLE PRECISION
  - NUMERIC(p, s)        -> NUMERIC(p, s)
  - BOOLEAN (0/1)        -> BOOLEAN
  - TEXT                 -> TEXT
  - SQLite TEXT columns that actually hold dates (start_date, finish_date,
    statement_date, due_date, payment_date) -> DATE, and the ones holding
    clock times (the travel *_time columns) -> TIME. See note 4.
  - DATE                 -> DATE, ISO-8601 (YYYY-MM-DD)
  - TIMESTAMP            -> TIMESTAMPTZ(0) (see notes 3 and 4)
  - BLOB (payslip PDFs)  -> BYTEA

Four deliberate departures from a literal translation:

  1. ``app_user.username`` is ``UNIQUE COLLATE NOCASE`` in SQLite, which has
     no direct Postgres equivalent on a plain TEXT column. The case-
     insensitive *uniqueness* is preserved with a UNIQUE INDEX on
     ``LOWER(username)``. Case-insensitive *lookups* (``WHERE username = ?``
     matching a different case) are NOT preserved -- Postgres compares TEXT
     case-sensitively -- so queries need ``LOWER(username) = LOWER(?)`` when
     the API is eventually pointed at Postgres.
  2. Identity sequences are resynced from ``MAX(id)``, not from
     ``sqlite_sequence``, because this database has duplicate
     ``sqlite_sequence`` rows for several tables (e.g. two
     ``calendar_day_override`` rows, 557 and 456) and the lower/stale value
     would hand out colliding ids on the first Postgres insert.
  3. The SQLite ``TIMESTAMP`` columns hold two different formats, because
     two different writers produced them: 1,903 naive ``YYYY-MM-DD HH:MM:SS``
     values from SQLite's own ``CURRENT_TIMESTAMP`` default (which is UTC),
     and 201 timezone-aware ISO-8601 values written by the app from Python
     (all of them ``+00:00``). Every value is therefore UTC, so the columns
     become ``TIMESTAMPTZ`` and the session is pinned to UTC for the copy --
     that reads the naive strings as UTC and keeps the offset on the aware
     ones. Plain ``TIMESTAMP`` would silently drop the ``+00:00`` and leave
     the column's meaning dependent on the reader's timezone.
  4. Types are the normalised ones, so a rebuild from SQLite lands on exactly
     the schema ``backend/scripts/normalize_time_types.py`` produced rather
     than quietly reverting it:

       - timestamps are ``TIMESTAMPTZ(0)`` (whole seconds). Those two SQLite
         writers also disagreed on precision -- microseconds on 201 rows, none
         on the other 1,903 -- and since ``.isoformat()`` omits a zero
         fraction, one column rendered two different shapes. Pinning the
         precision is what stops the next INSERT reintroducing the split.
       - the date/time-bearing TEXT columns get real DATE/TIME types, so
         Postgres validates and compares them and the API renders ISO-8601
         (note this makes a stored ``'07:15'`` render as ``'07:15:00'``).

Foreign keys are added AFTER the data load rather than inline, so the copy
does not depend on insertion order and every FK is validated against the
real data as it is created.

Usage (from the repo root, with the venv active):

    python backend/scripts/migrate_sqlite_to_postgres.py

Reads the Postgres connection from ``.env.local`` at the repo root
(``DATABASE_URL_UNPOOLED`` preferred over ``DATABASE_URL``: the unpooled
endpoint avoids the pgbouncer session limits that bite on DDL and large
batched inserts). Note that ``DATABASE_URL`` in ``.env.local`` is the
Postgres URL, while ``backend/db.py`` reads ``DATABASE_URL`` as a *SQLite*
path from ``.env`` -- this script never exports it, so the two cannot
collide.

Options:

    --sqlite PATH     source SQLite file (default: <repo-root>/data/budget.sqlite)
    --pg URL          target Postgres URL (default: from --env-file)
    --env-file PATH   env file to read the URL from (default: .env.local)
    --replace         DROP and recreate tables that already exist
    --dry-run         create nothing; report what would be copied
"""

