def _table_names() -> list[str]:
    return [name for name, _ in _SCHEMA]


def _resolve_pg_url(env_file: Path, explicit: str | None) -> str:
    if explicit:
        return explicit
    try:
        from dotenv import dotenv_values
    except ImportError:
        sys.exit("python-dotenv is required to read the env file; pass --pg instead")
    if not env_file.is_file():
        sys.exit(f"env file not found: {env_file} (pass --pg URL instead)")
    values = dotenv_values(env_file)
    # Unpooled first: the pooled (pgbouncer) endpoint is unfriendly to DDL
    # and to the large batched inserts this script issues.
    url = (values.get("DATABASE_URL_UNPOOLED") or values.get("DATABASE_URL") or "").strip()
    if not url:
        sys.exit(f"no DATABASE_URL_UNPOOLED or DATABASE_URL in {env_file}")
    if not url.startswith(("postgres://", "postgresql://")):
        sys.exit(f"{env_file} DATABASE_URL is not a Postgres URL")
    return url


def _sqlite_columns(scon: sqlite3.Connection, table: str) -> list[str]:
    return [r[1] for r in scon.execute(f'PRAGMA table_info("{table}")')]


def _convert(table: str, columns: list[str], rows: list[tuple]) -> list[tuple]:
    """Adapt SQLite values that Postgres will not take as-is."""
    import psycopg2

    bool_idx = [i for i, c in enumerate(columns) if (table, c) in _BOOL_COLUMNS]
    blob_idx = [i for i, c in enumerate(columns) if (table, c) in _BYTEA_COLUMNS]
    blank_idx = [i for i, c in enumerate(columns) if (table, c) in _BLANK_TO_NULL_COLUMNS]
    if not bool_idx and not blob_idx and not blank_idx:
        return rows
    out = []
    for row in rows:
        r = list(row)
        for i in bool_idx:
            if r[i] is not None:
                r[i] = bool(r[i])
        for i in blob_idx:
            if r[i] is not None:
                r[i] = psycopg2.Binary(r[i])
        for i in blank_idx:
            if isinstance(r[i], str) and not r[i].strip():
                r[i] = None
        out.append(tuple(r))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Copy the SQLite budget database into PostgreSQL."
    )
    ap.add_argument("--sqlite", type=Path, default=_DEFAULT_SQLITE_PATH)
    ap.add_argument("--pg", default=None)
    ap.add_argument("--env-file", type=Path, default=_DEFAULT_ENV_FILE)
    ap.add_argument("--replace", action="store_true", help="DROP and recreate existing tables")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    try:
        import psycopg2
        from psycopg2.extras import execute_values
    except ImportError:
        sys.exit("psycopg2 is required: pip install psycopg2-binary")

    if not args.sqlite.is_file():
        sys.exit(f"SQLite file not found: {args.sqlite}")
    pg_url = _resolve_pg_url(args.env_file, args.pg)

    scon = sqlite3.connect(f"file:{args.sqlite}?mode=ro", uri=True)
    src_counts = {
        t: scon.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0] for t in _table_names()
    }
    print(f"source: {args.sqlite}")
    print(f"target: {pg_url.split('@')[1].split('/')[0]}")
    print(f"tables: {len(_SCHEMA)}, rows: {sum(src_counts.values()):,}\n")

    if args.dry_run:
        for t in _table_names():
            print(f"  would copy {t:28} {src_counts[t]:>6,} rows")
        scon.close()
        return 0

    pcon = psycopg2.connect(pg_url)
    pcon.autocommit = False
    cur = pcon.cursor()
    try:
        # The naive SQLite timestamps are UTC; pin the session so Postgres
        # reads them as UTC rather than as whatever the client's zone is.
        cur.execute("SET TIME ZONE 'UTC'")
        cur.execute(
            "SELECT tablename FROM pg_tables WHERE schemaname='public' AND tablename = ANY(%s)",
            (_table_names(),),
        )
        existing = [r[0] for r in cur.fetchall()]
        if existing and not args.replace:
            sys.exit(
                f"target already has {len(existing)} of these tables "
                f"({', '.join(existing[:5])}{'...' if len(existing) > 5 else ''}).\n"
                "Re-run with --replace to drop and recreate them."
            )
        if existing:
            print(f"dropping {len(existing)} existing table(s)")
            for t in reversed(_table_names()):
                cur.execute(f'DROP TABLE IF EXISTS "{t}" CASCADE')

        print("creating tables")
        for name, body in _SCHEMA:
            cur.execute(f'CREATE TABLE "{name}" (\n{body}\n)')

        print("copying rows")
        copied: dict[str, int] = {}
        for table in _table_names():
            cols = _sqlite_columns(scon, table)
            collist = ", ".join(f'"{c}"' for c in cols)
            total = 0
            cursor = scon.execute(f'SELECT {collist} FROM "{table}"')
            # payslip carries multi-hundred-KB PDFs; a smaller page keeps the
            # single INSERT statement well under Postgres' limits.
            page = 50 if table == "payslip" else 1000
            while True:
                rows = cursor.fetchmany(page)
                if not rows:
                    break
                execute_values(
                    cur,
                    f'INSERT INTO "{table}" ({collist}) VALUES %s',
                    _convert(table, cols, rows),
                    page_size=page,
                )
                total += len(rows)
            copied[table] = total
            print(f"  {table:28} {total:>6,}")

        print("adding foreign keys")
        for tbl, col, ref_tbl, ref_col, on_delete in _FOREIGN_KEYS:
            cur.execute(
                f'ALTER TABLE "{tbl}" ADD CONSTRAINT "fk_{tbl}_{col}" '
                f'FOREIGN KEY ("{col}") REFERENCES "{ref_tbl}" ("{ref_col}") '
                f"ON DELETE {on_delete}"
            )

        print("creating indexes")
        for stmt in _INDEXES:
            cur.execute(stmt)

        print("resyncing identity sequences")
        for table in _IDENTITY_TABLES:
            cur.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f'COALESCE((SELECT MAX(id) FROM "{table}"), 1), '
                f'(SELECT COUNT(*) FROM "{table}") > 0)'
            )

        mismatches = [t for t in _table_names() if copied[t] != src_counts[t]]
        if mismatches:
            raise RuntimeError(f"row count mismatch, rolling back: {mismatches}")

        pcon.commit()
        print(f"\ncommitted {sum(copied.values()):,} rows across {len(copied)} tables")
    except Exception:
        pcon.rollback()
        print("\nROLLED BACK - no changes were made to Postgres", file=sys.stderr)
        raise
    finally:
        cur.close()
        pcon.close()
        scon.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
